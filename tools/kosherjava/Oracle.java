// Generates tests/zmanim-oracle.json from KosherJava Zmanim 2.5.0 (open source), used only as a
// development-time check of src/engines/zmanim.ts. Run:  npm run oracle:zmanim
// (needs a JDK and tools/kosherjava/lib/zmanim-2.5.0.jar from Maven Central).
//
// Keys match the opinion ids in src/content/zmanimOpinions.ts. Degree-based zmanim use the generic
// getSunriseOffsetByDegrees / getSunsetOffsetByDegrees (geometric, no refraction), so the definition
// is identical to ours. Fixed-minute zmanim are offsets from sea-level sunrise / sunset, as in KosherJava.

import com.kosherjava.zmanim.AstronomicalCalendar;
import com.kosherjava.zmanim.ComplexZmanimCalendar;
import com.kosherjava.zmanim.util.GeoLocation;

import java.text.SimpleDateFormat;
import java.util.*;

public class Oracle {
    record City(String id, double lat, double lon, double elev) {}

    public static void main(String[] args) {
        TimeZone tz = TimeZone.getTimeZone("Asia/Jerusalem");
        List<City> cities = List.of(
            new City("jerusalem", 31.778, 35.235, 750),
            new City("haifa", 32.794, 34.990, 0),
            new City("eilat", 29.558, 34.952, 0));
        String[] dates = { "2025-03-20", "2025-06-21", "2025-09-22", "2025-12-21",
                           "2026-03-20", "2026-06-21", "2026-09-23", "2026-12-21" };
        SimpleDateFormat iso = new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSSX");
        iso.setTimeZone(TimeZone.getTimeZone("UTC"));

        StringBuilder out = new StringBuilder();
        out.append("{\n  \"_about\": \"KosherJava Zmanim 2.5.0 (NOAA calculator), Asia/Jerusalem. Generated by tools/kosherjava/Oracle.java. Tolerance 1 minute.\",\n  \"cases\": [\n");
        boolean firstCase = true;
        for (City c : cities) {
            for (String d : dates) {
                String[] p = d.split("-");
                GeoLocation geo = new GeoLocation(c.id(), c.lat(), c.lon(), c.elev(), tz);
                ComplexZmanimCalendar z = new ComplexZmanimCalendar(geo);
                z.getCalendar().set(Integer.parseInt(p[0]), Integer.parseInt(p[1]) - 1, Integer.parseInt(p[2]));

                Date seaRise = z.getSeaLevelSunrise(), seaSet = z.getSeaLevelSunset();
                Map<String, Date> m = new LinkedHashMap<>();
                m.put("alot_16_1", z.getAlos16Point1Degrees());
                m.put("alot_19_75", z.getSunriseOffsetByDegrees(AstronomicalCalendar.GEOMETRIC_ZENITH + 19.75));
                m.put("alot_72", z.getAlos72());
                m.put("alot_90", z.getAlos90());
                m.put("misheyakir_10_2", z.getMisheyakir10Point2Degrees());
                m.put("misheyakir_11", z.getMisheyakir11Degrees());
                m.put("sunrise_mishor", seaRise);
                m.put("sunrise_elevation", z.getSunrise());
                m.put("shma_gra", z.getSofZmanShmaGRA());
                m.put("shma_mga_72", z.getSofZmanShmaMGA72Minutes());
                m.put("shma_mga_16_1", z.getSofZmanShmaMGA16Point1Degrees());
                m.put("tefila_gra", z.getSofZmanTfilaGRA());
                m.put("tefila_mga_72", z.getSofZmanTfilaMGA72Minutes());
                m.put("tefila_mga_16_1", z.getSofZmanTfilaMGA16Point1Degrees());
                m.put("chatzot", z.getSunTransit());
                m.put("mincha_gedola_gra", z.getMinchaGedola());
                m.put("mincha_gedola_mga_72", z.getMinchaGedola72Minutes());
                m.put("mincha_gedola_mga_16_1", z.getMinchaGedola16Point1Degrees());
                m.put("mincha_ketana_gra", z.getMinchaKetana());
                m.put("mincha_ketana_mga_72", z.getMinchaKetana72Minutes());
                m.put("mincha_ketana_mga_16_1", z.getMinchaKetana16Point1Degrees());
                m.put("plag_gra", z.getPlagHamincha());
                m.put("plag_mga_72", z.getPlagHamincha72Minutes());
                m.put("plag_mga_16_1", z.getPlagHamincha16Point1Degrees());
                m.put("sunset_mishor", seaSet);
                m.put("sunset_elevation", z.getSunset());
                m.put("tzeit_8_5", z.getTzaisGeonim8Point5Degrees());
                m.put("tzeit_7_083", z.getTzaisGeonim7Point083Degrees());
                m.put("tzeit_6_45", z.getTzaisGeonim6Point45Degrees());
                for (double min : new double[] { 13.5, 18, 20, 24 }) {
                    String k = "tzeit_" + (min == Math.floor(min) ? String.valueOf((int) min) : String.valueOf(min).replace('.', '_')) + "_min";
                    m.put(k, AstronomicalCalendar.getTimeOffset(seaSet, (long) (min * 60000)));
                }
                m.put("tzeit_rt_72", z.getTzais72());
                m.put("tzeit_rt_16_1", z.getTzais16Point1Degrees());

                if (!firstCase) out.append(",\n");
                firstCase = false;
                out.append("    { \"city\": \"").append(c.id()).append("\", \"lat\": ").append(c.lat())
                   .append(", \"lon\": ").append(c.lon()).append(", \"elevation\": ").append(c.elev())
                   .append(", \"date\": \"").append(d).append("\", \"zmanim\": {");
                boolean first = true;
                for (Map.Entry<String, Date> e : m.entrySet()) {
                    out.append(first ? "\n" : ",\n");
                    first = false;
                    out.append("      \"").append(e.getKey()).append("\": ")
                       .append(e.getValue() == null ? "null" : "\"" + iso.format(e.getValue()) + "\"");
                }
                out.append("\n    } }");
            }
        }
        out.append("\n  ]\n}\n");
        System.out.print(out);
    }
}
